import { execFileSync } from 'child_process';
import fs from 'fs';

console.log("Iniciando ETL de Gastos Operacionales (Asignaciones del Congreso)...");

// Simulación de lectura de Excel descargado por los bots de la Cámara/Senado
// En producción, aquí se procesaría el archivo de Transparencia de la Cámara
const gastosExtraidos = [
    { politico_id: 'dip-001', ano: 2026, mes: 3, categoria: 'Traslación y Viáticos', monto_bruto: 1250000, url_fuente: 'transparencia.camara.cl' },
    { politico_id: 'dip-002', ano: 2026, mes: 3, categoria: 'Arriendo de Sede', monto_bruto: 850000, url_fuente: 'transparencia.camara.cl' },
    { politico_id: 'sen-001', ano: 2026, mes: 3, categoria: 'Telefonía y Web', monto_bruto: 320000, url_fuente: 'transparencia.senado.cl' }
];

console.log(`Detectados ${gastosExtraidos.length} registros de gastos operacionales.`);

let sqlStatements = `-- Auto-generated by ingest-asignaciones-congreso.mjs\n`;

for (const gasto of gastosExtraidos) {
    const id = `gasto-${gasto.politico_id}-${gasto.ano}-${gasto.mes}-${gasto.categoria.replace(/\s+/g, '')}`;
    
    // UPSERT para gastos_operacionales
    sqlStatements += `
        INSERT INTO gastos_operacionales (id, politico_id, ano, mes, categoria, monto_bruto, url_fuente)
        VALUES ('${id}', '${gasto.politico_id}', ${gasto.ano}, ${gasto.mes}, '${gasto.categoria}', ${gasto.monto_bruto}, '${gasto.url_fuente}')
        ON CONFLICT(id) DO UPDATE SET 
            monto_bruto=excluded.monto_bruto,
            url_fuente=excluded.url_fuente;
    `;
}

// Guardar el archivo SQL temporalmente
const sqlFilePath = 'data/tmp_gastos_operacionales.sql';
fs.writeFileSync(sqlFilePath, sqlStatements);

console.log("Ejecutando UPSERT en la base de datos D1 remota...");

try {
    const out = execFileSync('npx', [
        'wrangler', 'd1', 'execute', 'transparencia-db',
        '--remote',
        '--file', sqlFilePath
    ], { encoding: 'utf8', shell: true });
    console.log(out);
    console.log("[OK] Gastos Operacionales ingresados exitosamente en D1.");
} catch (e) {
    console.error("Error actualizando D1:", e.message);
    if (e.stdout) console.log(e.stdout);
    if (e.stderr) console.error(e.stderr);
    process.exit(1);
} finally {
    if (fs.existsSync(sqlFilePath)) fs.unlinkSync(sqlFilePath);
}
