import { execFileSync } from 'child_process';
import fs from 'fs';

console.log("Iniciando ETL de Auto-Descubrimiento del Directorio del Estado...");

// 1. Simulación de extracción de datos oficiales (ej. desde gob.cl o InfoProbidad)
// En un caso real, aquí iría un crawler a gob.cl/ministerios
const ministeriosDetectados = [
    { sigla: 'MININTERIOR', nombre: 'Ministerio del Interior y Seguridad Pública', ministro: 'Carolina Tohá Morales' },
    { sigla: 'MINREL', nombre: 'Ministerio de Relaciones Exteriores', ministro: 'Alberto van Klaveren Stork' },
    { sigla: 'MINDEF', nombre: 'Ministerio de Defensa Nacional', ministro: 'Maya Fernández Allende' },
    { sigla: 'MINHACIENDA', nombre: 'Ministerio de Hacienda', ministro: 'Mario Marcel Cullell' },
    { sigla: 'SEGPRES', nombre: 'Ministerio Secretaría General de la Presidencia', ministro: 'Álvaro Elizalde Soto' },
    { sigla: 'SEGEGOB', nombre: 'Ministerio Secretaría General de Gobierno', ministro: 'Camila Vallejo Dowling' }
];

console.log(`Detectados ${ministeriosDetectados.length} ministerios vigentes.`);

let sqlStatements = `-- Auto-generated by ingest-directorio-estado.mjs\n`;

for (const min of ministeriosDetectados) {
    const id = min.sigla.toLowerCase();
    
    // UPSERT para servicios_publicos
    sqlStatements += `
        INSERT INTO servicios_publicos (id, nombre, sigla, tipo_organo, director_jefe_actual)
        VALUES ('${id}', '${min.nombre}', '${min.sigla}', 'Ministerio', '${min.ministro}')
        ON CONFLICT(id) DO UPDATE SET 
            nombre=excluded.nombre,
            director_jefe_actual=excluded.director_jefe_actual;
    `;
}

// Guardar el archivo SQL temporalmente
const sqlFilePath = 'data/tmp_directorio.sql';
fs.writeFileSync(sqlFilePath, sqlStatements);

console.log("Ejecutando UPSERT en la base de datos D1 remota...");

try {
    const out = execFileSync('npx', [
        'wrangler', 'd1', 'execute', 'transparencia-db',
        '--remote',
        '--file', sqlFilePath
    ], { encoding: 'utf8', shell: true });
    console.log(out);
    console.log("[OK] Directorio del Estado actualizado exitosamente en D1.");
} catch (e) {
    console.error("Error actualizando D1:", e.message);
    if (e.stdout) console.log(e.stdout);
    if (e.stderr) console.error(e.stderr);
    process.exit(1);
} finally {
    if (fs.existsSync(sqlFilePath)) fs.unlinkSync(sqlFilePath);
}
